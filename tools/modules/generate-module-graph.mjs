/*
 * The module graph of the site's code, for preloading (no build step bundles the modules, so a
 * module's imports are only discovered once it has loaded: each import level is a network round
 * trip). Generates:
 * - head.html: <link rel="modulepreload"> for every module scripts.js imports (statically,
 *   directly or not), so they load in parallel with scripts.js instead of level by level;
 * - scripts/module-graph.js: per block, the modules its JavaScript imports beyond those, which
 *   scripts.js preloads when the block is on the page (preloadBlockModules).
 * Run `npm run build:modules` after changing an import; test/modules checks both are current.
 */
import {
  readFileSync, readdirSync, existsSync, writeFileSync,
} from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const START = '<!-- modulepreload: generated by npm run build:modules -->';
const END = '<!-- /modulepreload -->';

/** the static imports of a module (relative specifiers), resolved to absolute paths */
function importsOf(file, cache) {
  if (cache.has(file)) return cache.get(file);
  const source = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const found = [...source.matchAll(/^\s*(?:import|export)\s+(?:[^'"]*?\s+from\s+)?['"](\.{1,2}\/[^'"]+)['"]/gm)]
    .map((m) => resolve(dirname(file), m[1]));
  cache.set(file, found);
  return found;
}

/** the module and everything it imports statically, in a stable order */
function closureOf(file, cache, out = new Set()) {
  if (out.has(file)) return out;
  out.add(file);
  importsOf(file, cache).forEach((dep) => closureOf(dep, cache, out));
  return out;
}

/**
 * @param {string} [root] the repository
 * @returns {{ head: string[], blocks: Object<string, string[]>, styled: string[] }} module paths
 *   relative to the code base; the blocks that have a stylesheet
 */
export function buildModuleGraph(root = ROOT) {
  const cache = new Map();
  const rel = (file) => relative(root, file).split('\\').join('/');
  const scripts = closureOf(resolve(root, 'scripts/scripts.js'), cache);
  // aem.js and scripts.js themselves are in head.html already
  const head = [...scripts].map(rel).filter((p) => !['scripts/aem.js', 'scripts/scripts.js'].includes(p)).sort();
  const blocks = {};
  const styled = [];
  readdirSync(resolve(root, 'blocks')).sort().forEach((name) => {
    if (existsSync(resolve(root, `blocks/${name}/${name}.css`))) styled.push(name);
    const file = resolve(root, `blocks/${name}/${name}.js`);
    if (!existsSync(file)) return;
    const own = [...closureOf(file, cache)].filter((f) => !scripts.has(f)).map(rel).sort();
    if (own.length) blocks[name] = own;
  });
  return { head, blocks, styled };
}

/** scripts/module-graph.js: the modules as one list and each block's as indexes into it */
export function renderGraphModule({ blocks, styled = [] }) {
  const modules = [...new Set(Object.values(blocks).flat())].sort();
  const index = Object.fromEntries(Object.entries(blocks)
    .map(([name, paths]) => [name, paths.map((p) => modules.indexOf(p))]));
  const list = modules.map((m) => `  '${m}',`).join('\n');
  const key = (name) => (/^[a-z]+$/.test(name) ? name : `'${name}'`);
  const map = Object.entries(index).map(([name, ids]) => `  ${key(name)}: [${ids.join(', ')}],`).join('\n');
  return `/*
 * Generated by \`npm run build:modules\` (tools/modules/generate-module-graph.mjs): do not edit.
 * The modules each block's JavaScript imports beyond those of scripts.js, for preloading them in
 * parallel (preloadBlockModules in scripts.js) instead of one import level after the other, and
 * the blocks with a stylesheet.
 */
const MODULES = [
${list}
];

const BLOCKS = {
${map}
};

/**
 * The modules of a block (paths relative to the code base), its own JavaScript included.
 * @param {string} name the block name
 * @returns {string[]}
 */
export default function blockModules(name) {
  return (BLOCKS[name] || []).map((i) => MODULES[i]);
}

const STYLED = new Set([
${styled.map((name) => `  '${name}',`).join('\n')}
]);

/**
 * The stylesheet of a block (path relative to the code base), if it has one.
 * @param {string} name the block name
 * @returns {string}
 */
export function blockStylesheet(name) {
  return STYLED.has(name) ? \`blocks/\${name}/\${name}.css\` : '';
}
`;
}

/** head.html with the modulepreload links of scripts.js's imports (replacing earlier ones) */
export function renderHead(html, { head }) {
  const links = head.map((p) => `<link rel="modulepreload" nonce="aem" href="/${p}"/>`).join('\n');
  const block = `${START}\n${links}\n${END}`;
  const at = html.indexOf(START);
  if (at >= 0) return `${html.slice(0, at)}${block}${html.slice(html.indexOf(END) + END.length)}`;
  // after the render-blocking stylesheet, which keeps its place first in the queue
  const anchor = '<link rel="stylesheet" href="/styles/styles.css"/>';
  if (!html.includes(anchor)) throw new Error('head.html: styles.css link not found');
  return html.replace(anchor, `${anchor}\n${block}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const graph = buildModuleGraph();
  // the graph module is imported by scripts.js: generate it before the head list includes it
  writeFileSync(resolve(ROOT, 'scripts/module-graph.js'), renderGraphModule(graph));
  const final = buildModuleGraph();
  writeFileSync(resolve(ROOT, 'scripts/module-graph.js'), renderGraphModule(final));
  const headFile = resolve(ROOT, 'head.html');
  writeFileSync(headFile, renderHead(readFileSync(headFile, 'utf8'), final));
  // eslint-disable-next-line no-console
  console.log(`head.html: ${final.head.length} modulepreload links; scripts/module-graph.js: ${Object.keys(final.blocks).length} blocks, ${new Set(Object.values(final.blocks).flat()).size} modules`);
}
